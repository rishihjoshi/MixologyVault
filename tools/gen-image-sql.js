#!/usr/bin/env node
// Generates supabase/images.sql: sets recipes.image_filename from the photo
// whitelists in app.js (DRINK_PHOTOS + SHARED_PHOTOS, merged as app.js does).
// Run: node tools/gen-image-sql.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (f) => JSON.parse(fs.readFileSync(path.join(root, f), 'utf8'));
const app = fs.readFileSync(path.join(root, 'app.js'), 'utf8');

// Pull a `const NAME = { ... };` object literal out of app.js and eval it.
// These maps are static string whitelists, safe to evaluate.
const literal = (name) => {
  const m = app.match(new RegExp(`const ${name} = (\\{[\\s\\S]*?\\n\\});`));
  if (!m) throw new Error(`${name} not found in app.js`);
  return eval(`(${m[1]})`);
};

const photos = literal('DRINK_PHOTOS'); // id -> path (exact-drink photos)
const shared = literal('SHARED_PHOTOS'); // path -> [ids] (shared "look" photos)
for (const [src, ids] of Object.entries(shared)) {
  for (const id of ids) if (!Object.hasOwn(photos, id)) photos[id] = src;
}

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const recipes = [...read('cocktails.json'), ...read('mocktails.json')];

const rows = [];
let withPhoto = 0;
for (const r of recipes) {
  if (!Object.hasOwn(photos, r.id)) continue; // no photo -> leave null
  rows.push(`update recipes set image_filename = ${q(photos[r.id])} where id = ${q(r.id)};`);
  withPhoto++;
}

const sql = `-- Generated by tools/gen-image-sql.js — do not edit by hand.
begin;
${rows.join('\n')}
commit;
`;

const out = path.join(root, 'supabase', 'images.sql');
fs.writeFileSync(out, sql);
console.log(`wrote ${out}`);
console.log(`  recipes with a photo: ${withPhoto} / ${recipes.length}`);
